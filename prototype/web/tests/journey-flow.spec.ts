import { test, expect, type Page } from '@playwright/test'
import type { JourneyCase } from '../src/journey/case'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
async function begin(page: Page, fixture: string) {
  await page.goto('/?study=journey&fixture=' + fixture)
  await button(page, '이 상황으로 시작').click()
  await expect(page.getByText('이 기기에 보관됨', { exact: true })).toBeVisible()
}
async function stored(page: Page): Promise<JourneyCase> {
  await expect(page.getByText('이 기기에 보관됨', { exact: true })).toBeVisible()
  return page.evaluate(async () => {
    const path = '/src/journey/case-store.ts'
    const { loadCase } = await import(/* @vite-ignore */ path) as typeof import('../src/journey/case-store')
    const value = await loadCase(new URL(location.href).searchParams.get('case')!)
    if (!value) throw new Error('Expected a durable journey case')
    return value
  })
}

