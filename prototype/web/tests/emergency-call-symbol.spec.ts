import { expect, test } from '@playwright/test'

test('phone_symbol_follows_confirmed_call_state_without_a_ribbon', async ({ page }) => {
  await page.goto('/?study=emergency&scenario=SC01&scene=contact_unknown')
  const symbol = page.locator('.ac-call-label')
  const spectrum = page.locator('.ac-spectrum')
  await expect(symbol).toHaveCount(0)
  await expect(spectrum).toHaveCount(0)
  await page.getByRole('button', { name: '시연 event: 통화 연결 확인', exact: true }).click()
  await expect(symbol.locator('svg')).toBeVisible()
  await expect(page.getByRole('heading', { name: '119 통화 연결됨', exact: true })).toBeVisible()
  await expect(page.locator('[data-slot="car"] canvas')).toHaveCount(0)
  await expect(spectrum).toBeVisible()
  await expect(page.locator('.ac-call-content')).not.toContainText('접수는 아직 미확인이에요.')
  await expect(page.locator('.emergency-review-header')).toContainText('spectrum은 가상 음성 반응')
  await expect(page.locator('[data-request="rescue"]')).toContainText('통화 연결 · 접수 미확인')
  await page.getByRole('button', { name: '시연 event: 연결 끊김', exact: true }).click()
  await expect(symbol).toHaveCount(0)
  await expect(spectrum).toHaveCount(0)
  await expect(page.locator('[data-request="rescue"]')).toContainText('연결 미확인')
})

test('spectrum_respects_pause_and_reduced_motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/?study=emergency&scenario=SC01&scene=connected')
  const bar = page.locator('.ac-spectrum > i').first()
  await expect.poll(() => bar.evaluate(el => el.getAnimations()[0]?.playState)).toBe('running')
  await page.getByRole('button', { name: '시연 일시 중단', exact: true }).click()
  await expect.poll(() => bar.evaluate(el => el.getAnimations()[0]?.playState)).toBe('paused')
  await page.getByRole('button', { name: '시연 재개', exact: true }).click()
  await expect.poll(() => bar.evaluate(el => el.getAnimations()[0]?.playState)).toBe('running')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect.poll(() => bar.evaluate(el => el.getAnimations().length)).toBe(0)
  await expect(page.locator('[data-request="rescue"]')).toContainText('통화 연결 · 접수 미확인')
})
