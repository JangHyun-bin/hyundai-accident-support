import { test, expect, type Page } from '@playwright/test'
import type { JourneyCase } from '../src/journey/case'

const primary = (page: Page) => page.getByTestId('journey-primary')
const step = (page: Page, number: number) => expect(page.getByTestId('journey-flow')).toHaveAttribute('data-step', String(number))
async function stored(page: Page): Promise<JourneyCase> {
  await expect(page.getByText('이 기기에 보관됨', { exact: true })).toBeVisible()
  return page.evaluate(async () => {
    const path = '/src/journey/case-store.ts'
    const { loadCase } = await import(path)
    return loadCase(new URL(location.href).searchParams.get('case')!)
  })
}
async function start(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: '이 상황으로 시작', exact: true }).click()
  await step(page, 1)
  await expect(page.getByRole('list', { name: '사고 대응 진행' }).getByRole('listitem')).toHaveCount(7)
  await primary(page).click()
  await page.getByRole('button', { name: '시연 event: 통화 연결 확인', exact: true }).click()
  await step(page, 2)
  await primary(page).click()
  await step(page, 3)
}
async function record(page: Page) {
  await primary(page).click()
  await step(page, 4)
  await primary(page).click()
  await step(page, 5)
}

test('default representative journey uses persisted facts through all seven stages, retry, BACK and call end', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await start(page)
  for (const checkbox of await page.getByRole('group', { name: '안전 확인 항목' }).getByRole('checkbox').all()) await checkbox.check()
  await step(page, 3)
  expect((await stored(page)).safetyActions.some(item => item.id === 'safe-arrival')).toBe(false)
  await record(page)
  await expect(primary(page)).toBeDisabled()
  await page.getByRole('button', { name: '직접 입력', exact: true }).click()
  await page.getByRole('textbox', { name: '사고 기록', exact: true }).fill('정차 중 오른쪽에서 충격을 느꼈어요.')
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  await primary(page).click()
  await step(page, 6)
  await primary(page).click()
  await page.getByRole('textbox', { name: '수신처', exact: true }).fill('내 보험사')
  await page.getByRole('checkbox', { name: /남긴 이야기 1/ }).check()
  await page.getByRole('button', { name: '선택한 내용 미리보기', exact: true }).click()
  await page.getByRole('button', { name: '이 내용으로 요청', exact: true }).click()
  const approved = await stored(page)
  const first = approved.submissions.find(item => item.agency === 'insurance')!
  expect(first.transport).toBe('approved')
  expect(first.status).toBe('checking')
  await primary(page).click()
  await expect(page.getByRole('button', { name: '이전 단계', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '시연 event: 보험사 전송 실패', exact: true }).click()
  await step(page, 6)
  await page.getByRole('button', { name: '이전 단계', exact: true }).click()
  await step(page, 5)
  await expect(page.getByRole('textbox', { name: '사고 기록', exact: true })).toHaveValue('정차 중 오른쪽에서 충격을 느꼈어요.')
  await primary(page).click()
  await primary(page).click()
  await page.getByRole('button', { name: '시연 event: 보험사 전송 완료', exact: true }).click()
  await step(page, 7)
  await expect(page.getByTestId('flow-board')).toHaveAttribute('data-target', 'sending')
  const sent = await stored(page)
  const attempts = sent.submissions.filter(item => item.agency === 'insurance')
  expect(attempts).toHaveLength(2)
  expect(attempts[0].status).toBe('failed')
  expect(attempts[1].id).not.toBe(attempts[0].id)
  expect(attempts[1].payload).toEqual(first.payload)
  expect(attempts[1].status).toBe('sent')
  expect(attempts[1].externalReceipt).toBeNull()
  expect(sent.submissions.find(item => item.id === sent.activeSubmissionIds.rescue)?.call).toBe('connected')
  await page.reload()
  await step(page, 7)
  await expect(page.getByTestId('flow-board')).toHaveAttribute('data-target', 'sending')
  await page.getByRole('button', { name: '시연 event: 통화 종료 확인', exact: true }).click()
  await expect(page.getByTestId('flow-board')).toHaveAttribute('data-target', 'calm')
  await page.getByRole('button', { name: '시연 event: 보험사 접수 확인', exact: true }).click()
  expect((await stored(page)).emergency.requests.insurance).toBe('received')
  await primary(page).click()
  await expect(page.locator('[data-journey-stage]')).toHaveAttribute('data-journey-stage', 'follow-up')
  expect(errors).toEqual([])
})

test('scene switches retain unsaved text, replay position, the case, and product URL', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await start(page)
  await record(page)
  await page.getByRole('button', { name: '직접 입력', exact: true }).click()
  const input = page.getByRole('textbox', { name: '사고 기록', exact: true })
  await input.fill('아직 저장하지 않은 기록')
  const node = await input.elementHandle()
  const caseId = new URL(page.url()).searchParams.get('case')
  const scene = page.getByTestId('journey-flow').locator('.ss-surface')
  await scene.getByRole('button', { name: '주변 상황 보기', exact: true }).click()
  await scene.getByRole('button', { name: '사고 재생', exact: true }).click()
  await scene.getByRole('slider', { name: '사고 시점 이동', exact: true }).fill('-2')
  await scene.getByRole('button', { name: '전방 시점', exact: true }).click()
  await scene.getByRole('button', { name: '내 차 상태로', exact: true }).click()
  await scene.getByRole('button', { name: '주변 상황 보기', exact: true }).click()
  await scene.getByRole('button', { name: '사고 재생', exact: true }).click()
  await expect(scene.getByRole('slider', { name: '사고 시점 이동', exact: true })).toHaveValue('-2')
  await expect(input).toHaveValue('아직 저장하지 않은 기록')
  expect(await node!.evaluate(element => element.isConnected)).toBe(true)
  expect(new URL(page.url()).searchParams.get('case')).toBe(caseId)
  expect(new URL(page.url()).searchParams.has('study')).toBe(false)
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  expect((await stored(page)).statements[0].text).toBe('아직 저장하지 않은 기록')
})
