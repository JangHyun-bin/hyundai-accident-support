test('a photo draft keeps its DOM and blob across scene and urgent response switches', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await start(page)
  await record(page)
  await page.getByRole('button', { name: '사진 남기기', exact: true }).click()
  await page.getByRole('button', { name: '현장 전체 사진', exact: true }).click()
  const png = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 20; canvas.height = 20; return canvas.toDataURL('image/png').split(',')[1] })
  await page.getByLabel('사진 파일 선택', { exact: true }).setInputFiles({ name: 'draft.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
  const photo = page.getByRole('img', { name: '저장 전 현장 전체 사진', exact: true })
  await expect(photo).toBeVisible()
  const node = await photo.elementHandle()
  const url = await photo.getAttribute('src')
  await page.getByRole('button', { name: '주변 상황 보기', exact: true }).click()
  await page.getByRole('button', { name: '전방 시점', exact: true }).click()
  await page.getByRole('button', { name: '시연 event: 위험 정보', exact: true }).click()
  await primary(page).click()
  await expect(photo).toBeVisible()
  expect(await photo.getAttribute('src')).toBe(url)
  expect(await node!.evaluate(element => element.isConnected)).toBe(true)
  await page.getByRole('button', { name: '후속 처리 보기', exact: true }).click()
  await step(page, 5)
  await expect(photo).toBeVisible()
  await page.getByRole('button', { name: '이 사진 사용', exact: true }).click()
  expect((await stored(page)).evidence.filter(item => item.kind === 'photo' && item.availability === 'available')).toHaveLength(1)
})
