import {journeyControl} from './helpers/journey-controls'
import { test, expect, type Locator, type Page } from '@playwright/test'
import type { JourneyCase } from '../src/journey/case'

const primary = (page: Page) => page.getByTestId('journey-primary')
const step = (page: Page, number: number) => expect(page.getByTestId('journey-flow')).toHaveAttribute('data-step', String(number))
async function stored(page: Page): Promise<JourneyCase> {
  await expect(page.getByText('이 기기에 보관됨', { exact: true })).toBeVisible()
  return page.evaluate(async () => {
    const path = '/src/journey/case-store.ts'
    const { loadCase } = await import(path)
    return loadCase(new URL(location.href).searchParams.get('case')!)
  })
}
async function start(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: '이 상황으로 시작', exact: true }).click()
  await step(page, 1)
  await expect(page.getByRole('list', { name: '사고 대응 진행' }).getByRole('listitem')).toHaveCount(7)
  await page.getByRole('button', { name: '다친 사람이 있거나 위험해요', exact: true }).click()
  await step(page, 2)
  await expect(page.getByTestId('flow-board')).toHaveAttribute('data-target', 'emergency')
  await page.getByRole('button', { name: '119에 연결', exact: true }).click()
  await page.getByRole('button', { name: /^(?:다음 · )?시연 event: 통화 연결 확인$/, exact: true }).click()
  await step(page, 2)
  await primary(page).click()
  await step(page, 3)
}
async function record(page: Page) {
  await primary(page).click()
  await step(page, 4)
  await primary(page).click()
  await step(page, 5)
}
async function focusedAfterLayout(page: Page, heading: Locator) {
  await expect(heading).toBeFocused({ timeout: 10000 })
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  await expect(heading).toBeFocused()
}

test('the journey opens on a situation check, shows 119 only for an emergency and never calls by itself', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: '이 상황으로 시작', exact: true }).click()
  await step(page, 1)
  const flow = page.getByTestId('journey-flow')
  const call = page.locator('[data-cell=emergency]').getByRole('button', { name: '119에 연결', exact: true })
  await expect(call).toBeHidden()
  await expect(primary(page)).toBeDisabled()
  await page.clock.runFor(15000)
  await expect(flow).toHaveAttribute('data-call', 'idle')
  await page.getByRole('button', { name: '급한 위험은 없어요', exact: true }).click()
  await step(page, 3)
  await expect(call).toBeHidden()
  await record(page)
  await expect(call).toBeHidden()
  const value = await stored(page)
  expect(value.activeSubmissionIds.rescue).toBeNull()
  expect(value.submissions.filter(item => item.agency === 'rescue')).toHaveLength(0)
  await page.getByRole('button', { name: '이전 단계', exact: true }).click()
  await step(page, 4)
  await page.getByRole('button', { name: '다친 사람이 있거나 위험해요', exact: true }).click()
  await step(page, 2)
  await expect(page.getByTestId('flow-board')).toHaveAttribute('data-target', 'emergency')
  await expect(call).toBeVisible()
  await page.clock.runFor(15000)
  await expect(flow).toHaveAttribute('data-call', 'idle')
  expect((await stored(page)).submissions.filter(item => item.agency === 'rescue')).toHaveLength(0)
  await call.click()
  await expect(flow).toHaveAttribute('data-call', 'connecting')
  await expect.poll(async () => (await stored(page)).submissions.filter(item => item.agency === 'rescue').length).toBe(1)
})

