test('the report evidence drawer opens inside the app window and traps and returns focus', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 1600, height: 900 })
  await start(page)
  await record(page)
  await page.getByRole('button', { name: '직접 입력', exact: true }).click()
  await page.getByRole('textbox', { name: '사고 기록', exact: true }).fill('정차 중 오른쪽 차량과 부딪혔어요.')
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  await (await journeyControl(page, '시연 event: 사고 자료 확보')).click()
  await expect(page.locator('button[aria-label="시연 event: 사고 자료 확보"]')).toBeEnabled()
  await (await journeyControl(page, '시연 event: 경위서 초안')).click()
  await primary(page).click()
  await page.getByRole('button', { name: '경위서', exact: true }).click()
  const trigger = page.getByRole('article', { name: '문장 1', exact: true }).getByRole('button', { name: '근거 보기', exact: true })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: '문장의 근거', exact: true })
  await expect(drawer).toBeVisible()
  const app = page.locator('[data-presentation=pleos] .ac-vehicle-content').filter({ has: drawer })
  const window = (await app.boundingBox())!, box = (await drawer.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(window.x)
  expect(box.y).toBeGreaterThanOrEqual(window.y)
  expect(box.x + box.width).toBeLessThanOrEqual(window.x + window.width)
  expect(box.y + box.height).toBeLessThanOrEqual(window.y + window.height)
  await expect(drawer.getByRole('button', { name: '근거 닫기', exact: true })).toBeFocused()
  for (let index = 0; index < 8; index++) {
    await page.keyboard.press('Tab')
    expect(await page.evaluate(() => document.activeElement === document.body || !!document.activeElement?.closest('.journey-report-drawer'))).toBe(true)
  }
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await expect(trigger).toBeFocused()
})
