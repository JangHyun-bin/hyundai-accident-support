test('background updates preserve document scroll and editor focus',async({page})=>{
 await record(page)
 const input=page.getByRole('textbox',{name:'사고 기록',exact:true})
 await input.fill('작성 중인 기록')
 await input.focus()
 await page.evaluate(()=>{window.scrollTo(0,0);(window as unknown as {editorScrollCalls:number}).editorScrollCalls=0;const original=Element.prototype.scrollIntoView;Element.prototype.scrollIntoView=function(options){(window as unknown as {editorScrollCalls:number}).editorScrollCalls++;original.call(this,options)}})
 await clickWithoutScroll(page,'시연 event: 구호 접수 확인')
 await expect(input).toBeFocused()
 await clickWithoutScroll(page,'이전 단계')
 await page.getByTestId('journey-primary').evaluate((node:HTMLButtonElement)=>node.click())
 await expect(page.getByTestId('journey-flow')).toHaveAttribute('data-step','5')
 await expect.poll(()=>page.evaluate(()=>window.scrollY)).toBe(0)
 expect(await page.evaluate(()=>(window as unknown as {editorScrollCalls:number}).editorScrollCalls)).toBe(0)
})

test('urgent response preserves the last observable IME value before hiding the editor',async({page})=>{
 await record(page)
 const input=page.getByRole('textbox',{name:'사고 기록',exact:true})
 await input.fill('정차 중 ')
 await input.evaluate((node:HTMLTextAreaElement)=>{node.focus({preventScroll:true});node.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true,data:''}));Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value')!.set!.call(node,'정차 중 오른쪽');node.setSelectionRange(8,8);node.dispatchEvent(new CompositionEvent('compositionupdate',{bubbles:true,data:'오른쪽'}))})
 await clickWithoutScroll(page,'시연 event: 위험 정보')
 await expect(page.getByRole('button',{name:'주변을 확인했어요',exact:true})).toBeVisible()
 await clickWithoutScroll(page,'기록으로 돌아가기')
 await expect(input).toHaveValue('정차 중 오른쪽')
 expect(await input.evaluate((node:HTMLTextAreaElement)=>node.selectionStart)).toBe(8)
})

test('nonurgent BACK waits for compositionend while the active editor stays mounted',async({page})=>{
 await page.setViewportSize({width:360,height:800})
 await record(page)
 const input=page.getByRole('textbox',{name:'사고 기록',exact:true})
 await input.fill('작성 중')
 await input.dispatchEvent('compositionstart',{data:''})
 await clickWithoutScroll(page,'이전 단계')
 await expect(page.getByTestId('journey-flow')).toHaveAttribute('data-step','5')
 await input.dispatchEvent('compositionend',{data:'중'})
 await expect(page.getByTestId('journey-flow')).toHaveAttribute('data-step','4')
})
