import {journeyControl} from './helpers/journey-controls'
import {test,expect,type Page} from '@playwright/test'

async function record(page:Page){
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 await page.getByRole('button',{name:'이 상황으로 시작',exact:true}).click()
 await page.getByTestId('journey-primary').click()
 await page.getByRole('button',{name: /^(?:다음 · )?시연 event: 통화 연결 확인$/,exact:true}).click()
 for(let i=0;i<3;i++)await page.getByTestId('journey-primary').click()
 await expect(page.getByTestId('journey-flow')).toHaveAttribute('data-step','5')
 await page.getByRole('button',{name:'직접 입력',exact:true}).click()
}
const clickWithoutScroll=async(page:Page,name:string)=>(await journeyControl(page,name,true)).evaluate((node:HTMLButtonElement)=>node.click())

test('bounded shell reserves progress, task actions and urgent facts together',async({page})=>{
 await record(page)
 const shell=page.locator('.journey-flow [data-care-component=vehicle-shell]')
 await expect(shell.getByRole('list',{name:'사고 대응 진행'})).toBeVisible()
 await expect(shell.getByTestId('journey-primary')).toBeVisible()
 await clickWithoutScroll(page,'시연 event: 위험 정보')
 await expect(shell.getByRole('alert')).toContainText('위험 정보 확인 필요')
 await expect(shell.getByRole('button',{name:'위험 안내 확인',exact:true})).toBeVisible()
})

test('real editor retains draft, caret and its own scroll through BACK and urgent return',async({page})=>{
 await record(page)
 const input=page.getByRole('textbox',{name:'사고 기록',exact:true})
 await input.fill('앞 차량이 멈춰서 함께 정차했어요. '.repeat(40))
 const original=await input.elementHandle()
 const scroll=page.locator('#journey-record-editor .journey-workspace-scroll:visible')
 await expect(scroll).toBeVisible()
 expect(await scroll.evaluate(node=>node.scrollHeight>node.clientHeight)).toBe(true)
 const title=page.locator('#journey-record-editor .journey-editor-title:visible')
 const save=page.getByRole('button',{name:'기록 저장',exact:true})
 const titleTop=(await title.boundingBox())!.y,saveTop=(await save.boundingBox())!.y
 expect(await scroll.evaluate(node=>node.clientHeight)).toBeGreaterThanOrEqual(70)
 await input.evaluate((node:HTMLTextAreaElement)=>{node.setSelectionRange(3,8);node.focus({preventScroll:true})})
 await scroll.evaluate(node=>{node.scrollTop=120})
 const position=await scroll.evaluate(node=>node.scrollTop)
 expect((await title.boundingBox())!.y).toBe(titleTop)
 expect((await save.boundingBox())!.y).toBe(saveTop)
 await clickWithoutScroll(page,'이전 단계')
 await page.getByTestId('journey-primary').evaluate((node:HTMLButtonElement)=>node.click())
 await expect(page.getByTestId('journey-flow')).toHaveAttribute('data-step','5')
 await expect(input).toHaveValue('앞 차량이 멈춰서 함께 정차했어요. '.repeat(40))
 expect(await original!.evaluate(node=>node.isConnected)).toBe(true)
 expect(await input.evaluate((node:HTMLTextAreaElement)=>[node.selectionStart,node.selectionEnd])).toEqual([3,8])
 expect(await scroll.evaluate(node=>node.scrollTop)).toBe(position)
 await clickWithoutScroll(page,'시연 event: 위험 정보')
 await clickWithoutScroll(page,'기록으로 돌아가기')
 await expect(input).toHaveValue('앞 차량이 멈춰서 함께 정차했어요. '.repeat(40))
 expect(await scroll.evaluate(node=>node.scrollTop)).toBe(position)
})

