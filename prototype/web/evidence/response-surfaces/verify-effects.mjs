import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ channel: 'chrome', headless: true })
const key = 'response-surface-study-v1'
const effectKeys = ['chromatic', 'chromaticAngle', 'grain', 'grainSize', 'grainClumping', 'grainTone', 'grainSeed']
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1100 }, deviceScaleFactor: 2, reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://127.0.0.1:5173/?study=response-alts&focus=surface')
  const original = JSON.parse(await page.locator('.rs-values pre').textContent())
  for (const surface of Object.values(original)) for (const key of effectKeys) delete surface[key]
  const c02 = structuredClone(original)
  c02.safety.blur = 49; c02.safety.radius = 68; c02.safety.y = 56.5
  const old = { version: 1, draft: c02, presets: [{ name: 'C', surfaces: original }, { name: 'C_02', surfaces: c02 }] }
  const oldJSON = JSON.stringify(old)
  await page.evaluate(({key, oldJSON}) => localStorage.setItem(key, oldJSON), { key, oldJSON })
  await page.reload()
  await page.evaluate(() => document.fonts.ready)
  assert.equal(await page.locator('.rs-material').count(), 0, 'old presets start with effects off')
  assert.equal(await page.getByLabel('Preset 이름').inputValue(), 'C_02')
  assert.equal(await page.evaluate(key => localStorage.getItem(key), key), oldJSON, 'read must not rewrite user storage')
  assert.deepEqual(await page.getByLabel('불러오기', {exact:true}).locator('option').allTextContents(), ['편집 중인 조합', 'B″ Original', 'C', 'C_02'])
  const migrated = JSON.parse(await page.locator('.rs-values pre').textContent())
  assert.equal(migrated.call.grain, 0)
  assert.equal(migrated.safety.chromatic, 0)
  for (const surface of Object.values(migrated)) for (const key of effectKeys) delete surface[key]
  assert.deepEqual(migrated, c02)

  const texture = () => page.locator('.rs-canvas feImage[result=grain]').getAttribute('href')
  await page.getByLabel('Grain 강도', {exact:true}).focus()
  await page.keyboard.press('End')
  await page.waitForFunction(() => document.querySelectorAll('.rs-material feImage[result=grain]').length === 2)
  const firstTexture = await texture()
  assert.ok(firstTexture.length > 100)
  const idList = await page.locator('.rs-material filter').evaluateAll(els => els.map(el => el.id))
  assert.equal(new Set(idList).size, idList.length)
  assert.equal(await page.locator('.rs-canvas .rc-call-center').evaluate(el => getComputedStyle(el).filter), 'none')
  assert.equal(await page.locator('.rs-canvas .rs-material').evaluate(el => getComputedStyle(el).pointerEvents), 'none')
  await page.getByLabel('Grain seed', {exact:true}).focus()
  await page.keyboard.press('ArrowRight')
  await page.waitForFunction(first => document.querySelector('.rs-canvas feImage[result=grain]')?.getAttribute('href') !== first, firstTexture)
  const secondTexture = await texture()
  assert.notEqual(secondTexture, firstTexture)
  await page.keyboard.press('ArrowLeft')
  await page.waitForFunction(first => document.querySelector('.rs-canvas feImage[result=grain]')?.getAttribute('href') === first, firstTexture)

  await page.getByLabel('색 분리', {exact:true}).focus()
  await page.keyboard.press('Home')
  for (let i = 0; i < 8; i++) await page.keyboard.press('ArrowRight')
  assert.equal(await page.locator('.rs-canvas feDisplacementMap').first().getAttribute('scale'), '-1.8')
  await page.getByLabel('Grain 강도', {exact:true}).focus()
  await page.keyboard.press('Home')
  for (let i = 0; i < 18; i++) await page.keyboard.press('ArrowRight')
  await page.waitForFunction(() => !!document.querySelector('.rs-canvas feImage[result=grain]'))
  await page.locator('.rs-canvas').screenshot({path:new URL('effects-desktop.png',import.meta.url).pathname})
  await page.getByRole('button', {name:'이 preset 업데이트'}).click()
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)
  const untouched = structuredClone(saved.presets[0].surfaces)
  for (const surface of Object.values(untouched)) for (const key of effectKeys) delete surface[key]
  assert.deepEqual(untouched, original, 'C stays unchanged when C_02 is updated')
  assert.equal(saved.presets[1].surfaces.call.chromatic, 2)
  assert.equal(saved.presets[1].surfaces.call.grain, 18)
  await page.reload()
  await page.waitForFunction(() => !!document.querySelector('.rs-canvas feImage[result=grain]'))
  assert.equal(await page.getByLabel('Grain 강도', {exact:true}).inputValue(), '18')
  await page.getByRole('button', {name:'원본 비교',exact:true}).click()
  assert.equal(await page.locator('.rs-material').count(), 0)
  assert.equal(await page.getByLabel('Grain 강도', {exact:true}).isDisabled(), true)
  await page.getByRole('button', {name:'편집 화면으로'}).click()
  await page.setViewportSize({width:393,height:900})
  await page.waitForFunction(() => !!document.querySelector('.rs-canvas feImage[result=grain]'))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.locator('.rs-canvas').screenshot({path:new URL('effects-mobile.png',import.meta.url).pathname})
  await page.getByRole('group', {name:'조절할 card'}).getByRole('button', {name:'대피 안내',exact:true}).click()
  assert.equal(await page.getByLabel('Grain 강도', {exact:true}).inputValue(), '0')
  await page.getByLabel('Grain 강도', {exact:true}).focus()
  await page.keyboard.press('End')
  await page.waitForFunction(() => !!document.querySelector('.rs-canvas .rc-safety feImage[result=grain]'))
  assert.equal(await page.locator('.rs-study > .rc-device .rc-call feDisplacementMap').first().getAttribute('scale'), '-1.8')
  assert.deepEqual(errors, [])
  console.log('PASS: legacy C/C_02 migration without read-time writes, values and names preserved, independent effects, deterministic grain, unique filters, crisp content, preset update/reload, original comparison, DPR2 and mobile.')
} finally { await browser.close() }
